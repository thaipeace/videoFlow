# Compile patterns once at module load for speed
_COMPILED_RULES: List[Tuple[re.Pattern, str]] = [
    (re.compile(pat, re.IGNORECASE), rep) for pat, rep in PRONUNCIATION_RULES
]


def normalize_vietnamese_pronunciation(text: str) -> str:
    """Normalize foreign sports and international names to natural Vietnamese phonetics for TTS."""
    if not text:
        return ""

    normalized = unicodedata.normalize("NFC", text)
    for pattern, replacement in _COMPILED_RULES:
        normalized = pattern.sub(replacement, normalized)

    return normalized
